// stores/uiStore.ts — 纯 UI 状态（面板开合、弹窗）
import { create } from 'zustand'
import type { WorkspaceArtifact } from '@shared/types'

export interface ArtifactPreviewTarget {
  botId: string
  artifact: WorkspaceArtifact
}

export type SettingsSection =
  | 'general'
  | 'providers'
  | 'bot'
  | 'scheduled'
  | 'avatars'
  | 'mcp'
  | 'skills'
  | 'debug'

interface UiState {
  browserPreview: { botId: string; taskId: string } | null
  setBrowserPreview: (target: { botId: string; taskId: string } | null) => void
  rightPanelOpen: boolean
  artifactPreview: ArtifactPreviewTarget | null
  artifactPreviewWidth: number
  /** Full-page presentation generated by this Bot; the current chat stays selected underneath. */
  agentHomeBotId: string | null
  /** 群聊中当前查看的成员 botId（单聊时为空，直接用会话 bot） */
  inspectedBotId: string | null
  settingsOpen: boolean
  settingsSection: SettingsSection
  setSettingsSection: (section: SettingsSection) => void
  profileOpen: boolean
  setProfileOpen: (v: boolean) => void
  newBotOpen: boolean
  newGroupOpen: boolean
  inviteChatId: string | null
  toggleRightPanel: () => void
  setRightPanelOpen: (v: boolean) => void
  setArtifactPreview: (target: ArtifactPreviewTarget | null) => void
  setArtifactPreviewWidth: (width: number) => void
  setAgentHomeBotId: (botId: string | null) => void
  inspectBot: (botId: string | null) => void
  setSettingsOpen: (v: boolean) => void
  setNewBotOpen: (v: boolean) => void
  setNewGroupOpen: (v: boolean) => void
  setInviteChatId: (id: string | null) => void
}

export const useUiStore = create<UiState>((set, get) => ({
  browserPreview: null,
  setBrowserPreview: (browserPreview) => set({ browserPreview, ...(browserPreview ? { rightPanelOpen: false, artifactPreview: null } : {}) }),
  rightPanelOpen: false,
  artifactPreview: null,
  artifactPreviewWidth: 520,
  agentHomeBotId: null,
  inspectedBotId: null,
  settingsOpen: false,
  settingsSection: 'general',
  setSettingsSection: (settingsSection) => set({ settingsSection }),
  profileOpen: false,
  setProfileOpen: (v) => set({ profileOpen: v }),
  newBotOpen: false,
  newGroupOpen: false,
  inviteChatId: null,
  toggleRightPanel: () => {
    const open = !get().rightPanelOpen
    set({
      rightPanelOpen: open,
      browserPreview: open ? null : get().browserPreview,
      artifactPreview: open ? null : get().artifactPreview,
    })
  },
  setRightPanelOpen: (v) =>
    set({
      rightPanelOpen: v,
      browserPreview: v ? null : get().browserPreview,
      artifactPreview: v ? null : get().artifactPreview,
    }),
  setArtifactPreview: (target) =>
    set({
      artifactPreview: target,
      browserPreview: target ? null : get().browserPreview,
      rightPanelOpen: target ? false : get().rightPanelOpen,
    }),
  setArtifactPreviewWidth: (width) => set({ artifactPreviewWidth: width }),
  setAgentHomeBotId: (agentHomeBotId) => set({
    agentHomeBotId,
    browserPreview: agentHomeBotId ? null : get().browserPreview,
    artifactPreview: agentHomeBotId ? null : get().artifactPreview,
  }),
  inspectBot: (botId) => {
    set({ inspectedBotId: botId, artifactPreview: null, browserPreview: null })
    if (botId) set({ rightPanelOpen: true })
  },
  setSettingsOpen: (v) => set({ settingsOpen: v }),
  setNewBotOpen: (v) => set({ newBotOpen: v }),
  setNewGroupOpen: (v) => set({ newGroupOpen: v }),
  setInviteChatId: (id) => set({ inviteChatId: id }),
}))
